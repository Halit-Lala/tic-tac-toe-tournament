

CREATE TABLE player (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    normalized_name VARCHAR(50) NOT NULL,

    CONSTRAINT uk_player_normalized_name
        UNIQUE (normalized_name)
);



CREATE TABLE tournament (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_x_id BIGINT NOT NULL,
    player_o_id BIGINT NOT NULL,
    format VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    winner_id BIGINT,

    CONSTRAINT fk_tournament_player_x
        FOREIGN KEY (player_x_id) REFERENCES player(id),

    CONSTRAINT fk_tournament_player_o
        FOREIGN KEY (player_o_id) REFERENCES player(id),

    CONSTRAINT fk_tournament_winner
        FOREIGN KEY (winner_id) REFERENCES player(id),

    CONSTRAINT ck_tournament_different_players
        CHECK (player_x_id <> player_o_id),

    CONSTRAINT ck_tournament_format
        CHECK (format IN ('BEST_OF_1', 'BEST_OF_3', 'BEST_OF_5')),

    CONSTRAINT ck_tournament_status
        CHECK (status IN ('CREATED', 'IN_PROGRESS', 'COMPLETED')),

    CONSTRAINT ck_tournament_winner
        CHECK (
            winner_id IS NULL
            OR winner_id IN (player_x_id, player_o_id)
        )
);



CREATE TABLE game (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT NOT NULL,
    game_number INTEGER NOT NULL,
    starting_symbol CHAR(1) NOT NULL,
    board_state VARCHAR(9) NOT NULL,
    status VARCHAR(20) NOT NULL,
    outcome VARCHAR(20),

    CONSTRAINT fk_game_tournament
        FOREIGN KEY (tournament_id) REFERENCES tournament(id),

    CONSTRAINT uk_game_tournament_number
        UNIQUE (tournament_id, game_number),

    CONSTRAINT ck_game_number
        CHECK (game_number BETWEEN 1 AND 5),

    CONSTRAINT ck_game_starting_symbol
        CHECK (starting_symbol IN ('X', 'O')),

    CONSTRAINT ck_game_board_state
        CHECK (board_state ~ '^[XO-]{9}$'),

    CONSTRAINT ck_game_status_outcome
        CHECK ((status = 'IN_PROGRESS' AND outcome IS NULL) OR (status = 'COMPLETED' AND outcome IS NOT NULL)
    )
);



CREATE INDEX idx_tournament_winner
    ON tournament(winner_id);